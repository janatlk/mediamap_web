import type { NextConfig } from "next";

import { LIMITS } from "./src/lib/attachment-rules";

/*
  Потолок тела запроса поднят под приложенные файлы: по умолчанию серверное
  действие принимает мегабайт, а запись экрана столько не весит никогда.

  Число берём из тех же правил, по которым файлы проверяются, — иначе форма
  начнёт обещать тридцать мегабайт, а запрос будет обрываться на первом.

  Чем платим: файл приезжает в память целиком. Для десятка сообщений в день
  это ничего не стоит, но при настоящей нагрузке загрузку надо будет увести
  на отдельный адрес и писать её потоком мимо действия.
*/
const nextConfig: NextConfig = {
  experimental: {
    serverActions: {
      bodySizeLimit: `${Math.round(LIMITS.TOTAL_BYTES / (1024 * 1024))}mb`,
    },
  },
};

export default nextConfig;
