/**
 * Годится ли строка для заголовка HTTP.
 *
 * Заголовки держат только латиницу. Ключ с кириллической буквой — а её
 * легко захватить при копировании — валил запрос невнятным TypeError про
 * ByteString: человек видел «сервис не ответил» и шёл искать неполадку в
 * сети. Проверяем сами и говорим прямо, что не так.
 */
export function headerSafe(value: string, what: string): string {
  /*
    Границы заданы кодами, а не буквами в скобках. Диапазон, записанный
    символами, при переносе файла между кодировками однажды уже уехал и
    начался с нулевого байта вместо пробела — то есть пропускал перевод
    строки в заголовок. Это уже не опечатка, а лазейка.

    0x20-0x7E — печатная латиница. Ниже идут управляющие символы, и среди
    них перевод строки: с ним в значении заголовка к запросу можно
    приписать второй заголовок. Выше 0x7E заголовок просто не примет.
  */
  for (const symbol of value) {
    const code = symbol.codePointAt(0) ?? 0;
    if (code < 0x20 || code > 0x7e) {
      throw new DetectorError(
        `в поле «${what}» есть знак, которого не может быть в ключе ` +
          `(код ${code}) — похоже, скопировано с лишним символом или ` +
          "переводом строки",
      );
    }
  }
  return value;
}
