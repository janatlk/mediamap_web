/*
  Общий вид ответа сторонних сервисов.

  Отвечают они по-разному: у одного число в поле type.ai_generated, у
  другого список классов с оценками, у третьего разбор в три захода. Здесь
  всё это приводится к одному, чтобы сравнивать их между собой можно было
  глазами, а не сверяя структуры JSON.

  raw оставляем целиком и намеренно. Пока мы решаем, верить ли этим
  сервисам, сырой ответ — единственное, по чему видно, что именно они
  сказали и не потерял ли наш переходник половину смысла.
*/

export type Credentials = Record<string, string>;

export type DetectorAnswer = {
  /**
   * Оценка «сгенерировано» от 0 до 1.
   *
   * Пусто, если сервис ответил, но числа в ответе не оказалось. Это не то
   * же самое, что ноль, и путать их нельзя: ноль означает «уверенно не
   * сгенерировано», пустота — «мы не поняли ответ».
   */
  score: number | null;
  /** Каким генератором, если сервис берётся назвать. */
  generator: string | null;
  /** Ответ сервиса как есть, для разбирательств. */
  raw: unknown;
  latencyMs: number;
};

/** Ошибка сервиса. Отдельным типом: отказ — это не оценка «ноль». */
export class DetectorError extends Error {
  constructor(
    message: string,
    /** Что вернул сервис — по нему видно, ключ ли плох или запрос. */
    readonly detail?: string,
  ) {
    super(message);
    this.name = "DetectorError";
  }
}

export type Detector = {
  /**
   * Проверка ключа.
   *
   * Настоящий запрос, а не разбор строки: единственный способ узнать, живой
   * ли ключ, — это спросить сервис. Шлём самую маленькую картинку, какую
   * он примет, чтобы проверка не стоила заметных денег.
   */
  probe(creds: Credentials): Promise<DetectorAnswer>;

  /** Разбор изображения. */
  detect(creds: Credentials, bytes: Buffer, mime: string): Promise<DetectorAnswer>;
};

