/*
  Стартовый набор источников и ключевых слов для сборщика.

  Это не настройка, а первое заполнение: дальше и то и другое живёт в базе и
  правится администратором через панель. Сюда заглядывают ровно один раз — при
  первом запуске сида на пустой базе.

  Каждая лента здесь проверена запросом: отвечает и отдаёт заметки. Ленты,
  которые я пробовал и которые не работают, перечислены в конце файла — чтобы
  их не завели заново, наткнувшись на те же адреса.

  Кого нет намеренно: изданий, которые сами являются предметом проверки на
  дезинформацию. Дайджест — это то, что мы читаем, и ставить туда такое
  издание по умолчанию значит принять решение за проект. Понадобится —
  администратор добавит сам, это одна строка в панели.

  Ключевые слова записаны основами, без окончаний: сравнение идёт по
  вхождению подстроки, и «дезинформац» ловит и «дезинформацию», и
  «дезинформации». Слишком короткую основу брать нельзя — «ложь» поймает
  «положение».
*/

export type SeedSource = {
  name: string;
  feedUrl: string;
  lang: string;
  /** Брать всю ленту, минуя ключевые слова. См. схему, поле takeAll. */
  takeAll?: boolean;
};

/*
  Запрос в Google News. Собирается функцией, а не пишется руками: адрес с
  процентными кодами нечитаем, и опечатку в нём замечают через неделю по
  пустой ленте.

  Google News сам ищет по словам, и это второй отбор поверх нашего. Так и
  задумано: без запроса лента отдавала бы всё подряд, а нашим ключевым
  словам пришлось бы отсеивать сотни заметок про погоду.
*/
const googleNews = (query: string, hl: string, ceid: string) =>
  `https://news.google.com/rss/search?q=${encodeURIComponent(query)}` +
  `&hl=${hl}&gl=KG&ceid=${ceid}`;

