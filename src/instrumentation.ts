/*
  Проверка окружения при запуске.

  Next вызывает register() один раз, до первого запроса. Это единственное
  место, где можно поймать неверную настройку до того, как её увидит человек.

  Проверяем немногое, но то, что ломается молча. Забытый SITE_URL не роняет
  сайт: страницы открываются, и заметить нечего — пока кто-нибудь не нажмёт
  «войти через Google» и не уедет на localhost, или пока заявитель не получит
  письмо со ссылкой, которая ведёт в никуда. Такую ошибку лучше получить
  сразу и громко, при выкладке, чем через неделю от растерянного человека.

  Остальное только сообщаем в журнал: без почты и без ML-сервиса сайт
  работает осмысленно, и решать, запускаться ли так, — не наше дело.
*/

export async function register(): Promise<void> {
  if (process.env.NEXT_RUNTIME !== "nodejs") return;

  const production = process.env.NODE_ENV === "production";
  const site = process.env.SITE_URL ?? "";

  if (production) {
    if (!site) {
      throw new Error(
        "SITE_URL не задан. Без него вход через Google уводит на localhost, " +
          "а в письмах заявителям стоят нерабочие ссылки. См. .env.example",
      );
    }

    if (site.includes("localhost") || site.includes("127.0.0.1")) {
      throw new Error(
        `SITE_URL=${site} — это адрес для разработки. На сервере он должен ` +
          "быть внешним адресом сайта, иначе вход и письма ведут в никуда.",
      );
    }
  }

  // Что включено, а что нет. Строчка в журнале при старте избавляет от
  // получаса догадок «почему не приходят письма».
  const выключено = [
    process.env.ML_SERVICE_URL ? null : "разбор моделью (ML_SERVICE_URL)",
    process.env.SMTP_HOST ? null : "письма заявителям (SMTP_HOST)",
    process.env.GOOGLE_CLIENT_ID ? null : "вход через Google",
  ].filter(Boolean);

  console.info(
    выключено.length
      ? `MediaMap: работает без — ${выключено.join(", ")}`
      : "MediaMap: все службы настроены",
  );
}
